test('imports, edits and exports current SDRF, downloads source, and browses run tabs', async ({ page }) => {
  test.setTimeout(120_000)
  const projectId = await importFixture(page, `GUI metadata ${crypto.randomUUID().slice(0, 8)}`)
  for (const tab of ['Files', 'Processing', 'Provenance', 'Summary', 'Spectra']) {
    await page.getByRole('navigation', { name: 'Run sections' }).getByRole('link', { name: tab, exact: true }).click()
  }
  const catalogState = page.locator('.spectrum-catalog-state strong')
  await expect(catalogState).toHaveText(/Indexed catalog|Compatibility mode/)
  if (await catalogState.textContent() === 'Compatibility mode') await page.getByRole('button', { name: 'Build catalog', exact: true }).click()
  await expect(catalogState).toHaveText('Indexed catalog', { timeout: 60_000 })
  await expect(page.getByRole('img', { name: 'centroid spectrum' })).toBeVisible()
  const sourceDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download source' }).click()
  expect(await (await sourceDownload).suggestedFilename()).toBe('gui.mgf')
  await page.goto(`/projects/${projectId}/metadata`)
  await page.locator('.project-details > summary').click()
  await page.getByLabel('Keywords, one per line').fill('gui\nreview')
  await page.getByRole('button', { name: 'Save project', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Project metadata saved')
  await page.getByRole('button', { name: 'Generate from project' }).click()
  await page.locator('.sdrf-columns > summary').click()
  await expect(page.getByLabel('Column 1', { exact: true })).toHaveValue('source name')
  await page.getByLabel('Column 1', { exact: true }).press('End')
  await page.getByLabel('Column 1', { exact: true }).pressSequentially(' extra')
  await expect(page.getByLabel('Column 1', { exact: true })).toHaveValue('source name extra')
  await page.getByLabel('Column 1', { exact: true }).fill('source name')
  await page.getByLabel('Row 1, source name, column 1', { exact: true }).fill('GUI edited sample')
  const downloaded = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export SDRF', exact: true }).click()
  const path = await (await downloaded).path()
  expect(await readFile(path!, 'utf8')).toContain('GUI edited sample')
  await page.getByLabel('Row 1, source name, column 1', { exact: true }).fill('GUI validated sample')
  await page.getByRole('button', { name: 'Validate now' }).click()
  await expect(page.getByRole('status')).toContainText(/SDRF validation passed|Validation found/, { timeout: 60_000 })
  const saved = await (await page.request.get(`/api/v1/projects/${projectId}/sdrf`, { headers: await authHeaders(page) })).json()
  expect(saved.rows[0].values[0]).toBe('GUI validated sample')
  await page.getByRole('button', { name: 'Add row', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Remove SDRF row 2' })).toBeVisible()
  await page.getByRole('button', { name: 'Remove SDRF row 2' }).click()
  await page.getByRole('button', { name: 'Save table' }).click()
  await expect(page.getByRole('status')).toContainText('Saved SDRF revision')
  page.once('dialog', dialog => dialog.accept('factor value[gui]'))
  await page.getByRole('button', { name: 'Add SDRF column' }).click()
  await page.getByRole('button', { name: /Factors/ }).click()
  await expect(page.getByLabel(/^Row 1, factor value\[gui\], column /)).toBeVisible()
  await page.getByRole('button', { name: /^Remove column \d+, factor value\[gui\]$/ }).click()
  const file = { name: 'gui.sdrf.tsv', mimeType: 'text/tab-separated-values', buffer: await readFile(path!) }
  await page.route('**/sdrf/import', route => route.fulfill({ status: 503, json: { detail: 'SDRF import unavailable' } }))
  await page.locator('input[type=file]').setInputFiles(file)
  await expect(page.getByRole('alert')).toContainText('SDRF import unavailable')
  await page.unroute('**/sdrf/import')
  await page.locator('input[type=file]').setInputFiles(file)
  await expect(page.getByRole('status')).toContainText('Imported 1 SDRF rows')
})

