import { expect, test, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

const username = process.env.SPECTARR_E2E_USERNAME ?? 'release-admin'
const password = process.env.SPECTARR_E2E_PASSWORD ?? 'release-rehearsal-admin-password'
const errors = new WeakMap<Page, string[]>()
test.beforeEach(async ({ page }) => {
  test.skip(process.env.SPECTARR_E2E_GUI !== 'true', 'Use a dedicated GUI test instance')
  errors.set(page, [])
  page.on('pageerror', error => errors.get(page)?.push(error.message))
  await page.goto('/')
  await page.getByLabel('Username').fill(username)
  await page.getByLabel('Password').fill(password)
  await page.getByRole('button', { name: 'Sign in' }).click()
  await expect(page.getByRole('heading', { name: 'MassSpec overview' })).toBeVisible()
})
test.afterEach(async ({ page }) => { expect(errors.get(page) ?? []).toEqual([]) })

async function authHeaders(page: Page) {
  return { Authorization: `Bearer ${await page.evaluate(() => sessionStorage.getItem('spectarr_access_token'))}` }
}

async function importFixture(page: Page, project: string) {
  await page.goto('/runs/import')
  await page.getByLabel('Project', { exact: true }).fill(project)
  await page.getByLabel('Experiment', { exact: true }).fill('GUI experiment')
  await page.getByLabel('Source files').setInputFiles({ name: 'gui.mgf', mimeType: 'application/octet-stream',
    buffer: Buffer.from('BEGIN IONS\nTITLE=gui\nPEPMASS=445.34\nCHARGE=2+\n100 20\n200 30\nEND IONS\n') })
  await page.getByRole('button', { name: 'Import 1 run' }).click()
  await expect(page.getByText('1 of 1 imported')).toBeVisible()
  await page.getByRole('link', { name: 'Open gui', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'gui', exact: true })).toBeVisible()
  return page.url().split('/projects/')[1].split('/')[0]
}

